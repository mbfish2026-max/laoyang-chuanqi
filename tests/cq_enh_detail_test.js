const T=require('./cq_harness')('cq_enh_detail_test'),{G,ok}=T;
G(`load();CQSys.createChar('强化短测','zs');S.lvl=60;calc();S.gold=1e8;addMat('heitie',100);addMat('heitie15',100);addMat('heitie20',100);addMat('zhuanyi',3);var a=genItem(1,{base:BASEM.shd1,q:1}),b=genItem(1,{base:BASEM.shd1,q:1}),c=genItem(1,{base:BASEM.glv1,q:1});S.bag.push(a,b,c);a.en=3;`);
ok(G(`cqEnhRate(3,'heitie15')===70&&cqEnhRate(3,'heitie20')===75&&cqEnhRate(0,'heitie20')===100`),'纯度加成有上限，旧矿不变');
ok(G(`cqEnhance(a.uid,{ore:'heitie20',roll:74}).ok&&matCount('heitie20')===96&&matCount('heitie')===100`),'高纯度成功率与扣料一致');
ok(G(`cqEnhance(b.uid,{ore:'bad'}).err==='无效黑铁矿'`),'非法纯度不消耗');
G(`a.en=9;a.en9=1;b.en=0;`);
ok(G(`cqEnhTransfer(a.uid,c.uid).to===8&&a.en===0&&c.en===8&&matCount('zhuanyi')===2&&!a.en9&&!c.en9`),'左右手镯转移损一级并清理光效标记');
ok(G(`!!cqEnhTransfer(c.uid,c.uid).err&&matCount('zhuanyi')===2`),'自身转移不扣料');
G(`var w=genItem(1,{base:BASEM.sw1,q:1});S.bag.push(w);`);
ok(G(`!!cqEnhTransfer(c.uid,w.uid).err&&c.en===8&&matCount('zhuanyi')===2`),'跨部位不可转移');
G(`S.eq.shield=null;S.eq.gloves=null;equip(a.uid,'gloves');equip(b.uid,'shield');`);
ok(G(`S.eq.gloves===a&&S.eq.shield===b`),'相同底材可分别穿两侧，旧键保留');
ok(G(`SLOTN.shield==='左手镯'&&SLOTN.gloves==='右手镯'`),'显示语义统一');
G(`addMat('heitie20',2);save();load();`);
ok(G(`matCount('heitie20')===98&&!!S.eq.shield&&!!S.eq.gloves`),'纯度与双槽存取不丢失');
ok(G(`cqOre(2,20).id==='heitie20'&&cqOre(2,15).id==='heitie15'&&cqOre(2).id==='heitie'`),'矿石按独立材料堆叠');
G(`CQSys.heroCreate('zs','强化英雄');var h1=genItem(1,{base:BASEM.shd1,q:1}),h2=genItem(1,{base:BASEM.shd1,q:1});S.bag.push(h1,h2);`);
ok(G(`CQSys.hero().lvl<itemReq(h1).lv&&CQSys.heroEquip(h1.uid,'gloves').err==='英雄等级不足'&&S.bag.includes(h1)&&!CQSys.hero().eq.gloves`),'低等级英雄不可穿戴手镯，物品留在背包');
G(`CQSys.hero().lvl=Math.max(itemReq(h1).lv,itemReq(h2).lv);var he1=CQSys.heroEquip(h1.uid,'gloves'),he2=CQSys.heroEquip(h2.uid,'shield');`);
ok(G(`he1.ok&&he1.slot==='gloves'&&he2.ok&&he2.slot==='shield'`),'英雄达到手镯需求等级后两侧穿戴均成功');
ok(G(`CQSys.hero().eq.gloves===h1&&CQSys.hero().eq.shield===h2`),'英雄也可把相同手镯穿两侧');
T.done();
